"""The registry of every tool: where it lives, how to open it, what it keeps."""
import json
from dataclasses import dataclass, field
from pathlib import Path


def _x(p: str) -> str:
    return str(Path(p).expanduser()) if p.startswith("~") else p


@dataclass(frozen=True)
class Tool:
    id: str
    name: str
    group: str
    what: str
    path: Path
    open: list[str]
    desktop: str | None
    repo: str
    status: str                      # how its status line is found: summary, netusage, doctor, web, files, git
    url: str | None = None
    files: list[Path] = field(default_factory=list)


@dataclass(frozen=True)
class Registry:
    tools: list[Tool]
    shared_dir: Path

    def get(self, tool_id: str) -> Tool:
        return next(t for t in self.tools if t.id == tool_id)


def load(path: Path) -> Registry:
    data = json.loads(Path(path).read_text())
    tools = [Tool(t["id"], t["name"], t["group"], t["what"], Path(_x(t["path"])), [_x(a) for a in t["open"]],
                  t.get("desktop"), t["repo"], t["status"], t.get("url"), [Path(_x(f)) for f in t.get("files", [])])
             for t in data["tools"]]
    return Registry(tools, Path(_x(data["shared_dir"])))


def write_tools_md(reg: Registry, out: Path, backlogs: Path) -> None:
    """TOOLS.md: one overview of every tool, generated from the registry."""
    lines = ["# My tools", "",
             "Generated by Tools Hub from `tools-hub/tools.json`; edit that file, not this one.", ""]
    for group in dict.fromkeys(t.group for t in reg.tools):
        lines += [f"## {group}", "", "| Tool | What it does | Folder | Repo | Backlog |", "|---|---|---|---|---|"]
        for t in (t for t in reg.tools if t.group == group):
            folder = str(t.path).replace(str(Path.home()), "~")
            rel = Path(backlogs).name
            lines.append(f"| **{t.name}** | {t.what} | `{folder}` | {t.repo} | [{rel}/{t.id}.md](tools-hub/{rel}/{t.id}.md) |")
        lines.append("")
    lines += [f"Shared data: `{str(reg.shared_dir).replace(str(Path.home()), '~')}`, one `<tool-id>.json` "
              "summary per tool, read by the Hub and by the other tools.", ""]
    Path(out).write_text("\n".join(lines))
